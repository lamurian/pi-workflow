// ─── Test-tool ensure step (T2/T7) ──────────────────────────────────────────
// Registry-aware generation of the local test extension. Decision rule:
// a `test` tool from ANOTHER path owns the name -> stop (existing); the file
// carries the GENERATED marker -> regenerate in place; the file exists without
// the marker -> hand-written, never overwritten, reported; else generate.
// The generated extension is ORCHESTRATOR-OWNED (T7): it is never declared in
// the contract, never auto-injected into any allowlist, and units may not
// write it — the orchestrator regenerates and commits it itself.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";
import type {
  TestSuite,
  TestSuiteDetection,
  TestSuiteSource,
} from "./test-tool-detect.ts";
import { saveState } from "./state.ts";
import type { ContractV2, GateResult, GateSuiteResult, WorkflowState } from "./state.ts";
import { deriveUnitScope } from "./contract-derive.ts";
import { commitTestExtensionChore, type ChoreCommitResult } from "./test-extension-chore.ts";
import { RETRY_BUDGET } from "./commit-gate.ts";

// ── Constants ─────────────────────────────────────────────────────────────────

/** Marker comment every generated test extension carries (guards regeneration). */
export const GENERATED_MARKER =
  "// GENERATED by pi-workflow /finalize — do not edit";

/** Repo-relative path of the generated test extension. */
export const TEST_EXTENSION_RELATIVE = ".pi/extensions/test.ts";

/** Default per-suite wall-clock budget in ms (PI_TEST_TIMEOUT_MS override). */
export const DEFAULT_SUITE_TIMEOUT_MS = 300000;

/** Per-suite output tail cap in characters (labeled tail of the suite output). */
export const OUTPUT_TAIL_CHARS = 4000;

// ── Types ─────────────────────────────────────────────────────────────────────

/** Result of the ensure step for one save_task run (T7: no files entry). */
export interface EnsureTestToolResult {
  /** Where the effective test tool came from (persisted as state.testTool.source). */
  source: TestSuiteSource;
  /** Suites the generated tool runs (empty when none or an external tool owns the name). */
  suites: TestSuite[];
  /** Absolute path of the generated file — present only when a file was written. */
  path?: string;
  /** One-line detection evidence for the save_task output. */
  message: string;
}

// ── Path resolution ───────────────────────────────────────────────────────────

/**
 * Resolve the generated test extension path for a working directory.
 *
 * @param cwd - Repository working directory.
 * @returns The absolute path of `.pi/extensions/test.ts`, or undefined when absent.
 */
export function resolveTestExtensionPath(cwd: string): string | undefined {
  const full = join(resolve(cwd), ".pi", "extensions", "test.ts");
  return existsSync(full) ? full : undefined;
}

// ── Generation ────────────────────────────────────────────────────────────────

/**
 * Whether a suite accepts the structured scope/run filters (T7).
 *
 * Only Go test suites are filterable: `scope` maps to package patterns
 * (`./<path>/...`) and `run` maps to `-run <regex>`. Every other suite either
 * runs unfiltered (no filter passed) or is skipped on a filter pass with an
 * explicit report line. Computed at generation time and embedded per suite, so
 * the generated file stays self-contained.
 *
 * @param suite - The detected suite (label + argv).
 * @returns True for `go test ...` suites.
 */
export function isFilterableSuite(suite: TestSuite): boolean {
  return suite.argv[0] === "go" && suite.argv[1] === "test";
}

/**
 * Generate the self-contained test extension source for the given suites.
 *
 * The output carries the GENERATED marker, imports nothing (node:fs is loaded
 * lazily inside execute), and default-exports a factory registering the `test`
 * tool with structured filters: `scope?: string[]` (repo-relative paths, each
 * mapped to `./<path>/...` for Go suites) and `run?: string` (mapped to
 * `-run <regex>` for Go suites). A no-args run defaults to the unit payload's
 * derived packages (PI_UNIT_FILE); a filter pass skips non-filterable suites
 * with an explicit line and carries the filtered-run header. Every suite runs
 * sequentially via `pi.exec` (argv arrays, never shell strings) with a
 * per-suite `PI_TEST_TIMEOUT_MS` budget (default 300000), labeled output
 * capped at a 4000-char tail, and an isError result when any run suite fails.
 *
 * @param suites - The suites the generated tool runs.
 * @returns The extension source text (plain JS-compatible TypeScript).
 */
export function generateTestExtension(suites: readonly TestSuite[]): string {
  const suiteLines = suites
    .map(
      (suite) =>
        `  { "label": ${JSON.stringify(suite.label)}, "argv": ${JSON.stringify(suite.argv)}, "filterable": ${isFilterableSuite(suite)} }`,
    )
    .join(",\n");
  return `${GENERATED_MARKER}
//
// Registers the \`test\` tool: runs every detected test suite sequentially via
// pi.exec (argv arrays, never shell strings) and reports a labeled output tail
// per suite. Regenerated by pi-workflow — change the suites via
// \`implement.testCommands\` in workflow.json instead of editing this file.
//
// Structured filters (iteration only, never verification):
//   test()           — default scope: the unit payload's derived packages
//                      (PI_UNIT_FILE) on filterable suites, everything else too
//   test(scope, run) — scope: repo-relative paths, each mapped to ./<path>/...;
//                      run: a -run <regex> for filterable (Go) suites.
// A filter pass skips non-filterable suites and never satisfies the done criteria.

/** Detected test suites (label + argv + filterability), frozen at generation time. */
const SUITES = [
${suiteLines}
];

/** Per-suite wall clock budget: PI_TEST_TIMEOUT_MS, ${DEFAULT_SUITE_TIMEOUT_MS}ms default. */
function suiteTimeoutMs() {
  const raw = Number(process.env.PI_TEST_TIMEOUT_MS);
  return Number.isFinite(raw) && raw > 0 ? raw : ${DEFAULT_SUITE_TIMEOUT_MS};
}

/** Cap a suite's combined output to its last ${OUTPUT_TAIL_CHARS} characters. */
function tail(text) {
  return text.length > ${OUTPUT_TAIL_CHARS} ? "\\u2026" + text.slice(-${OUTPUT_TAIL_CHARS}) : text;
}

/**
 * Read the orchestrator-written unit payload (PI_UNIT_FILE, with the legacy
 * PI_CONTRACT_GUARD_FILE fallback) for the default package scope.
 *
 * @returns The payload's unit slice, or null when absent or invalid.
 */
async function readUnitPayload() {
  try {
    const file = process.env.PI_UNIT_FILE || process.env.PI_CONTRACT_GUARD_FILE;
    if (!file) return null;
    const { readFileSync } = await import("node:fs");
    const parsed = JSON.parse(readFileSync(file, "utf8"));
    const unit = parsed && parsed.unit;
    if (!unit || !Array.isArray(unit.packages)) return null;
    return unit;
  } catch (err) {
    return null;
  }
}

/** True when a scope entry is a safe repo-relative path (T7). */
function validScopeEntry(entry) {
  return (
    typeof entry === "string" &&
    /^[a-zA-Z0-9._/-]+$/.test(entry) &&
    !entry.startsWith("-") &&
    entry.indexOf("..") === -1
  );
}

/** The argv one suite runs with under the resolved filter (T7). */
function suiteArgv(suite, packages, run) {
  if (!suite.filterable) return suite.argv;
  const extra = suite.argv.slice(2).filter((arg) => arg !== "./...");
  const patterns =
    packages && packages.length > 0
      ? packages.map((p) => (p === "." ? "./..." : "./" + p + "/..."))
      : ["./..."];
  return ["go", "test"]
    .concat(run ? ["-run", run] : [])
    .concat(patterns)
    .concat(extra);
}

/**
 * Register the \`test\` tool on the host extension API.
 *
 * @param pi - ExtensionAPI of the host process.
 */
export default function testToolExtension(pi) {
  pi.registerTool({
    name: "test",
    label: "Run tests",
    description:
      "Run the project's test suites sequentially and report pass/fail with a " +
      "labeled output tail. The optional scope/run filters are iteration only — " +
      "a filtered run never satisfies the done criteria. Errors when any suite fails.",
    parameters: {
      type: "object",
      properties: {
        scope: {
          type: "array",
          items: { type: "string" },
          description:
            "Repo-relative path filter: filterable (Go) suites run only these " +
            "packages (each mapped to ./<path>/...); non-filterable suites are skipped.",
        },
        run: {
          type: "string",
          description:
            "Test-name regex for filterable (Go) suites, passed as -run <regex>; " +
            "non-filterable suites are skipped.",
        },
      },
      additionalProperties: false,
    },
    async execute(toolCallId, params, signal, onUpdate, ctx) {
      const scope = params && Array.isArray(params.scope) ? params.scope : undefined;
      const run = params && typeof params.run === "string" && params.run ? params.run : undefined;
      // Structured params only (T7): a malformed scope entry rejects the whole
      // call before anything runs — no free-form argv smuggling.
      if (scope) {
        for (const entry of scope) {
          if (!validScopeEntry(entry)) {
            return {
              content: [{
                type: "text",
                text:
                  "invalid scope entry: " + JSON.stringify(entry) +
                  " — scope entries must be repo-relative paths matching " +
                  "[a-zA-Z0-9._/-], with no leading '-' and no '..'. Nothing was run.",
              }],
              isError: true,
            };
          }
        }
      }
      const filtered = Boolean((scope && scope.length > 0) || run);
      // Default scope for a no-args run: the unit payload's derived packages.
      const packages =
        scope && scope.length > 0
          ? scope
          : filtered
            ? undefined
            : ((await readUnitPayload()) || {}).packages;
      const timeout = suiteTimeoutMs();
      const sections = [];
      const failures = [];
      let ran = 0;
      for (const suite of SUITES) {
        if (!suite.filterable && filtered) {
          sections.push(
            "## " + suite.label + "\\nsuite '" + suite.label +
              "' skipped (not filterable) — filtered iteration run, not verification",
          );
          continue;
        }
        const argv = suiteArgv(suite, packages, run);
        ran++;
        let result;
        try {
          result = await pi.exec(argv[0], argv.slice(1), { cwd: ctx.cwd, timeout });
        } catch (err) {
          failures.push(suite.label);
          sections.push(
            "## " + suite.label + "\\nspawn failed: " + String((err && err.message) || err),
          );
          continue;
        }
        const ok = result.code === 0 && !result.killed;
        if (!ok) failures.push(suite.label);
        const out =
          tail([result.stdout, result.stderr].filter(Boolean).join("\\n")) || "(no output)";
        sections.push(
          "## " + suite.label +
            "\\nexit " + result.code +
            (result.killed ? " (killed)" : "") +
            "\\n" + out,
        );
      }
      const summary =
        failures.length === 0
          ? "all " + ran + " suite(s) passed"
          : failures.length + "/" + ran + " suite(s) failed: " + failures.join("; ");
      // Every filtered result carries the header first (T7): n = suites run,
      // m = total suites known at generation time.
      const header = filtered
        ? "filtered run — " + ran + "/" + SUITES.length +
          " suites — does not satisfy the done criteria"
        : "";
      const text = (header ? header + "\\n" : "") + summary + "\\n\\n" + sections.join("\\n\\n");
      return failures.length === 0
        ? { content: [{ type: "text", text: text }] }
        : { content: [{ type: "text", text: text }], isError: true };
    },
  });
}
`;
}

// ── Orchestrator test gates (T8) ───────────────────────────────────────────

/** Result of one orchestrator-run gate: per-suite verdicts plus overall pass. */
export interface TestGateRun {
  /** True when every executed suite exited 0 without being killed. */
  passed: boolean;
  /** Per-suite verdicts with capped output tails. */
  suites: GateSuiteResult[];
}

/**
 * Resolve the per-suite wall-clock budget for gate runs.
 *
 * @param env - Environment map (defaults to process.env); injectable for tests.
 * @returns The timeout in ms (> 0).
 */
export function gateTimeoutMs(
  env: Record<string, string | undefined> = process.env,
): number {
  const raw = Number(env.PI_TEST_TIMEOUT_MS);
  return Number.isFinite(raw) && raw > 0 ? raw : DEFAULT_SUITE_TIMEOUT_MS;
}

/**
 * Cap combined suite output to the gate tail budget.
 *
 * @param text - Raw combined stdout+stderr of one suite.
 * @returns The capped tail (marked with an ellipsis when truncated).
 */
function gateTail(text: string): string {
  return text.length > OUTPUT_TAIL_CHARS ? `\u2026${text.slice(-OUTPUT_TAIL_CHARS)}` : text;
}

/**
 * The argv one suite runs with inside a gate run (T8).
 *
 * Filterable (Go) suites get the scope packages mapped to `./<path>/...`
 * (`./...` when no scope is given); non-filterable suites always run their
 * plain argv unfiltered — a gate never passes a filter to them.
 *
 * @param suite - The detected suite (label + argv).
 * @param scope - Optional repo-relative package dirs (the scope gate).
 * @returns The argv the suite runs with.
 */
export function gateSuiteArgv(suite: TestSuite, scope?: readonly string[]): string[] {
  if (!isFilterableSuite(suite)) return suite.argv;
  const extra = suite.argv.slice(2).filter((arg) => arg !== "./...");
  const patterns =
    scope && scope.length > 0
      ? [...scope].map((p) => (p === "." ? "./..." : `./${p}/...`))
      : ["./..."];
  return ["go", "test"].concat(patterns).concat(extra);
}

/**
 * Run an orchestrator test gate over the given suites (T8).
 *
 * Runs every suite sequentially via pi.exec (argv arrays, never shell strings)
 * with the PI_TEST_TIMEOUT_MS budget — orchestrator-run, outside any unit's
 * tool call. With a `scope`, every filterable suite runs with the scoped
 * package patterns while every non-filterable suite runs unfiltered (the
 * per-task SCOPE GATE after each task commit); without a scope every suite
 * runs unfiltered (the FULL GATE before complete_implementation).
 *
 * @param pi     - ExtensionAPI used for exec.
 * @param cwd    - Repository working directory.
 * @param suites - state.testTool.suites to run.
 * @param scope  - Optional derived packages scope (scope gate); omitted = full gate.
 * @returns The per-suite verdicts and the overall pass flag.
 */
export async function runTestGate(
  pi: ExtensionAPI,
  cwd: string,
  suites: readonly TestSuite[],
  scope?: readonly string[],
): Promise<TestGateRun> {
  const timeout = gateTimeoutMs();
  const results: GateSuiteResult[] = [];
  for (const suite of suites) {
    const argv = gateSuiteArgv(suite, scope);
    const [cmd = "", ...rest] = argv;
    let execResult: { code: number; killed?: boolean; stdout?: string; stderr?: string };
    try {
      execResult = await pi.exec(cmd, rest, { cwd, timeout });
    } catch (err) {
      results.push({
        label: suite.label,
        passed: false,
        tail: `spawn failed: ${String((err as Error)?.message ?? err)}`,
      });
      continue;
    }
    const passed = execResult.code === 0 && !execResult.killed;
    results.push({
      label: suite.label,
      passed,
      tail:
        gateTail([execResult.stdout ?? "", execResult.stderr ?? ""].filter(Boolean).join("\n")) ||
        "(no output)",
    });
  }
  return { passed: results.every((r) => r.passed), suites: results };
}

/**
 * Build the fix-forward task text for a red scope gate (T8).
 *
 * The commit landed, but the orchestrator-run gate stayed red: the task is
 * not done and a fix-forward attempt goes through the retry path with this
 * text — gate report (failing suite + output tail) plus the original task.
 *
 * @param result   - The red gate result.
 * @param attempt  - 1-based fix-forward attempt number.
 * @param original - The original unit task text for this behavior.
 * @returns Rendered fix-forward task text.
 */
export function buildScopeGateFixTask(
  result: GateResult,
  attempt: number,
  original: string,
): string {
  return (
    `## Previous attempt failed (retry ${attempt}/${RETRY_BUDGET})\n` +
    `${renderGateReport(result, "scope gate")}\n\n` +
    `The scope gate is run by the ORCHESTRATOR after your commit landed — it is ` +
    `not your own test-tool call and cannot be satisfied by reporting success: ` +
    `every filterable suite runs with this task's derived package scope plus ` +
    `every non-filterable suite, unfiltered. Fix forward: make the failing suite ` +
    `pass with real code changes. Do NOT delete, skip, or weaken a test to turn ` +
    `the gate green.\n\n` +
    `## Original task\n` + original
  );
}

/**
 * Run the per-task SCOPE GATE for one committed task (T8).
 *
 * From `state.testTool.suites`: every filterable suite runs with the task's
 * derived packages scope, every non-filterable suite runs unfiltered — the
 * orchestrator's own exec, never the unit's tool call. Tasks with no tests
 * refs (empty derived packages) and sessions without suites get no gate
 * (manual-ness is derived, not declared).
 *
 * @param pi         - ExtensionAPI used for exec.
 * @param cwd        - Repository working directory.
 * @param contract   - The v2 contract the task scope derives from.
 * @param suites     - state.testTool.suites.
 * @param behaviorId - The committed task's id.
 * @returns The recorded gate result, or null when no gate applies.
 */
export async function runTaskScopeGate(
  pi: ExtensionAPI,
  cwd: string,
  contract: ContractV2,
  suites: readonly TestSuite[],
  behaviorId: string,
): Promise<GateResult | null> {
  if (suites.length === 0) return null;
  const scope = deriveUnitScope(contract, behaviorId);
  if (scope.packages.length === 0) return null;
  const gate = await runTestGate(pi, cwd, suites, scope.packages);
  return {
    behaviorId,
    scope: [...scope.packages],
    passed: gate.passed,
    suites: gate.suites,
    at: new Date().toISOString(),
  };
}

/**
 * Run and record the per-task scope gate after one landed commit (T8).
 *
 * Orchestrator-run, outside the unit's tool call: delegates to
 * {@link runTaskScopeGate} when the session carries a v2 contract, then
 * records the verdict on `state.gateResults` and persists it — the red
 * result is persisted while the behavior is still active, so a red gate
 * keeps the task open and the behavior loop steers fix-forward. Returns
 * null when no gate applies (v1 session, no suites, task with no tests
 * refs).
 *
 * @param pi         - ExtensionAPI used for exec and state persistence.
 * @param cwd        - Repository working directory.
 * @param state      - Current workflow state (mutated: gateResults).
 * @param behaviorId - The committed task's id.
 * @returns The recorded gate result, or null when no gate applies.
 */
export async function commitScopeGate(
  pi: ExtensionAPI,
  cwd: string,
  state: WorkflowState,
  behaviorId: string,
): Promise<GateResult | null> {
  if (!state.contractV2) return null;
  const result = await runTaskScopeGate(
    pi,
    cwd,
    state.contractV2,
    state.testTool?.suites ?? [],
    behaviorId,
  );
  if (result) {
    state.gateResults = { ...(state.gateResults ?? {}), [behaviorId]: result };
    saveState(pi, state);
  }
  return result;
}

/**
 * The halt text for a scope gate that stayed red past the retry budget (T8).
 *
 * @param result - The red gate result.
 * @returns The halt message: the task is not done, plus the gate report.
 */
export function redGateHaltText(result: GateResult): string {
  return (
    `Scope gate for ${result.behaviorId} stayed red after ${RETRY_BUDGET} fix-forward ` +
    `attempts — the task is not done.\n\n${renderGateReport(result, "scope gate")}`
  );
}

/**
 * The notification text for a red scope gate steering fix-forward (T8).
 *
 * @param result  - The red gate result.
 * @param attempt - The current fix-forward attempt number.
 * @returns One-line warning naming the failing suite count and retry position.
 */
export function redGateNotifyText(result: GateResult, attempt: number): string {
  return (
    `Scope gate red for ${result.behaviorId}: ` +
    `${result.suites.filter((s) => !s.passed).length} suite(s) failed — ` +
    `steering fix-forward (retry ${attempt}/${RETRY_BUDGET})`
  );
}

/**
 * Render one recorded gate result as report/investigation text (T8).
 *
 * Names the gate kind and verdict, the scope, every suite verdict, and the
 * full output tail of each failing suite — the text a red scope gate's
 * fix-forward attempt (or a refused completion) receives.
 *
 * @param result - The recorded gate result (a state.gateResults entry).
 * @param kind   - "scope gate" (per-task) or "full gate" (completion).
 * @returns Multi-line report text.
 */
export function renderGateReport(
  result: GateResult,
  kind: "scope gate" | "full gate",
): string {
  const failing = result.suites.filter((s) => !s.passed);
  const parts = [
    `## Orchestrator ${kind}: ${result.behaviorId} — ${result.passed ? "GREEN" : "RED"}`,
    "",
    `Scope: ${result.scope.length > 0 ? result.scope.join(", ") : "(all packages — unfiltered)"}`,
    `Suites: ${
      result.suites.length > 0
        ? result.suites.map((s) => `${s.label} ${s.passed ? "PASS" : "FAIL"}`).join("; ")
        : "(none)"
    }`,
    "",
  ];
  for (const f of failing) {
    parts.push(`### ${f.label} (FAIL) — output tail`, "", f.tail, "");
  }
  return parts.join("\n").replace(/\n+$/, "");
}

/**
 * The one-line gate evidence for mark_task_done (T8): scope + pass/fail.
 *
 * @param result - The recorded gate result (a state.gateResults entry).
 * @returns e.g. `orchestrator gate T1 — scope pkg/foo — passed (2/2 suites)`.
 */
export function formatGateEvidenceLine(result: GateResult): string {
  const passedCount = result.suites.filter((s) => s.passed).length;
  return (
    `orchestrator gate ${result.behaviorId} — scope ` +
    `${result.scope.length > 0 ? result.scope.join(", ") : "(all packages)"} — ` +
    `${result.passed ? "passed" : "failed"} (${passedCount}/${result.suites.length} suites)`
  );
}

// ── Ensure step ───────────────────────────────────────────────────────────────

/**
 * Registry-aware ensure step: generate or regenerate `.pi/extensions/test.ts`.
 *
 * Decision rule (precedence order):
 * 1. `pi.getAllTools()` shows a `test` tool from ANOTHER path -> stop; the
 *    external tool owns the name (source `existing`).
 * 2. No suites (source `none`) -> nothing to run, warn.
 * 3. The file exists WITHOUT the GENERATED marker -> hand-written: never
 *    overwritten, reported (source `existing`).
 * 4. The file carries the marker -> regenerate in place; else generate fresh.
 *
 * The generated extension is orchestrator-owned (T7): nothing is returned that
 * a caller could declare in a contract allowlist, and no git query runs.
 *
 * @param pi        - ExtensionAPI (tool registry).
 * @param cwd       - Repository working directory.
 * @param detection - Suite detection result (config override or manifest scan).
 * @returns The ensure outcome: effective source, suites, written path (when a
 *          file was written) and a one-line evidence message.
 */
export async function ensureTestTool(
  pi: ExtensionAPI,
  cwd: string,
  detection: TestSuiteDetection,
): Promise<EnsureTestToolResult> {
  const targetPath = join(resolve(cwd), ".pi", "extensions", "test.ts");

  // 1. Registry: an external `test` tool already owns the name.
  const tools = typeof pi.getAllTools === "function" ? pi.getAllTools() : [];
  const existing = tools.find((tool) => tool.name === "test");
  if (existing && resolve(existing.sourceInfo.path) !== targetPath) {
    return {
      source: "existing",
      suites: [],
      message:
        `test tool already registered from ${existing.sourceInfo.path} — ` +
        "no generation, the existing tool owns the name",
    };
  }

  // 2. Nothing to run.
  if (detection.source === "none" || detection.suites.length === 0) {
    return {
      source: "none",
      suites: [],
      message: "no test tool: no test suites detected (no manifest matched)",
    };
  }

  // 3. Existing file: marker decides regenerate vs hand-written refusal.
  let existingContent: string | null = null;
  if (existsSync(targetPath)) {
    try {
      existingContent = readFileSync(targetPath, "utf8");
    } catch {
      existingContent = null; // Unreadable: fall through and regenerate.
    }
  }
  if (existingContent !== null && !existingContent.includes(GENERATED_MARKER)) {
    return {
      source: "existing",
      suites: [],
      message:
        `test tool not generated: ${TEST_EXTENSION_RELATIVE} exists without the ` +
        "GENERATED marker (hand-written) — left untouched",
    };
  }

  // 4. Generate or regenerate.
  const content = generateTestExtension(detection.suites);
  mkdirSync(dirname(targetPath), { recursive: true });
  writeFileSync(targetPath, content);
  const verb = existingContent === null ? "generated" : "regenerated";
  const suiteList = detection.suites.map((suite) => suite.label).join(", ");
  return {
    source: detection.source,
    suites: detection.suites,
    path: targetPath,
    message:
      `test tool ${verb}: ${TEST_EXTENSION_RELATIVE} — runs ` +
      `${detection.suites.length} suite(s): ${suiteList}`,
  };
}

// ── Implement-start ensure + chore commit (T9) ──────────────────────────────

/** Outcome of the /implement-start test-extension ensure step (T9). */
export interface StartEnsureResult {
  /**
   * "landed" = the regenerated file was committed alone; "skipped" = nothing
   * to commit (no file written, or the file is unchanged); "aborted"/"failed"
   * = the caller must halt before any unit spawns.
   */
  kind: ChoreCommitResult["kind"];
  /** One-line evidence message from the ensure step. */
  message: string;
  /** Staged foreign paths that aborted the chore commit (aborted only). */
  otherPaths: string[];
  /** Halt text when the chore commit aborted or failed (empty otherwise). */
  investigation: string;
}

/**
 * Run the ensure step at /IMPLEMENT START and land the chore commit (T9).
 *
 * Regenerates `.pi/extensions/test.ts` from the session's recorded suites
 * (`state.testTool`, recorded by save_task; sessions without recorded suites
 * skip the step entirely — no re-detection) — the file is orchestrator-owned
 * and never writable by a unit. When the generated file changed it is
 * committed alone as `chore: regenerate test extension` via
 * commitTestExtensionChore: the commit may contain only the generated path;
 * any other staged path aborts it so the orchestrator halts instead of
 * sweeping foreign work into the chore commit.
 *
 * @param pi    - ExtensionAPI (tool registry + exec).
 * @param cwd   - Repository working directory.
 * @param state - Workflow state (supplies the recorded test suites).
 * @returns The ensure/chore outcome: kind, evidence message, abort paths,
 *          and the halt investigation when the chore commit aborted/failed.
 */
export async function ensureTestExtensionAtStart(
  pi: ExtensionAPI,
  cwd: string,
  state: Pick<WorkflowState, "testTool">,
): Promise<StartEnsureResult> {
  const recorded = state.testTool?.suites ?? [];
  if (recorded.length === 0) {
    return {
      kind: "skipped",
      message: "no test tool recorded in state.testTool — no start-time regeneration",
      otherPaths: [],
      investigation: "",
    };
  }
  const detection: TestSuiteDetection = {
    source: state.testTool?.source ?? "detected",
    suites: recorded,
  };
  const ensured = await ensureTestTool(pi, cwd, detection);
  if (!ensured.path) {
    return { kind: "skipped", message: ensured.message, otherPaths: [], investigation: "" };
  }
  const chore = await commitTestExtensionChore(pi, cwd, TEST_EXTENSION_RELATIVE);
  return {
    kind: chore.kind,
    message: `${ensured.message} — chore commit: ${chore.kind}`,
    otherPaths: chore.otherPaths,
    investigation: chore.investigation,
  };
}
