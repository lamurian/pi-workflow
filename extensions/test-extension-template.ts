// Renders the self-contained `.pi/extensions/test.ts`. The runtime helper
// block lives in test-extension-template-helpers.ts, the routing block in
// test-extension-template-routing.ts. Output must stay byte-identical across
// refactors (see __tests__/fixtures/test-extension.golden.txt).

import type { TestSuite } from "./test-tool-detect.ts";
import { GENERATED_MARKER } from "./test-extension-constants.ts";
import { generatedHelpersSource } from "./test-extension-template-helpers.ts";
import { generatedRoutingSource } from "./test-extension-template-routing.ts";

/**
 * Whether a suite accepts the structured scope/run filters (T7).
 *
 * Only Go test suites are filterable: `scope` maps to package patterns
 * (`./<path>/...`) and `run` maps to `-run <regex>`. Computed at generation
 * time; the gate (test-gate-run.ts) uses it, the generated tool routes by
 * language instead. The generated file stays self-contained.
 *
 * @param suite - The detected suite (label + argv).
 * @returns True for `go test ...` suites.
 */
export function isFilterableSuite(suite: TestSuite): boolean {
  return suite.argv[0] === "go" && suite.argv[1] === "test";
}

/**
 * Generate the self-contained test extension source for the given suites.
 *
 * The output carries the GENERATED marker, imports nothing (node:fs and
 * node:path are loaded lazily inside execute), and default-exports a factory
 * registering the `test` tool. Runs are routed per suite (plain-JS port of
 * suite-scope.ts routeSuites): a path goes only to the matching-language
 * suite whose cwd is the deepest ancestor, D paths are dropped, suites with
 * no routed paths are skipped with an explicit line. A no-args run routes the
 * unit payload's owned test files (unit.testFiles via PI_UNIT_FILE); a
 * `scope` param routes the given repo-relative paths instead and carries the
 * filtered-run header; `run` maps to `-run <regex>` on go test argv. Every
 * routed suite runs sequentially via `pi.exec` (argv arrays, never shell
 * strings) with cwd = join(payload repoRoot, suite.cwd) and a per-suite
 * `PI_TEST_TIMEOUT_MS` budget (default 300000), labeled output capped at a
 * 4000-char tail, and an isError result when any run suite fails.
 *
 * @param suites - The suites the generated tool runs.
 * @returns The extension source text (plain JS-compatible TypeScript).
 */
export function generateTestExtension(suites: readonly TestSuite[]): string {
  const suiteLines = suites
    .map((suite) => {
      const fields = [
        `"label": ${JSON.stringify(suite.label)}`,
        `"argv": ${JSON.stringify(suite.argv)}`,
        ...(suite.scope ? [`"scope": ${JSON.stringify(suite.scope)}`] : []),
        ...(suite.cwd ? [`"cwd": ${JSON.stringify(suite.cwd)}`] : []),
      ];
      return `  { ${fields.join(", ")} }`;
    })
    .join(",\n");
  return `${GENERATED_MARKER}
//
// Registers the \`test\` tool: routes the run's paths to the matching suites
// (language + deepest-ancestor cwd) and executes the routed ones sequentially
// via pi.exec (argv arrays, never shell strings) with a per-suite cwd,
// reporting a labeled output tail per suite. Regenerated by pi-workflow —
// change the suites via \`implement.testCommands\` in workflow.json instead of
// editing this file.
//
// Routing (iteration only, never verification):
//   test()           — default scope: the unit payload's owned test files
//                      (unit.testFiles via PI_UNIT_FILE)
//   test(scope, run) — scope: repo-relative paths routed per suite instead of
//                      the payload's testFiles; run: -run <regex> for go test.
// Suites with no routed paths are skipped with an explicit line; a filtered
// run never satisfies the done criteria.

/** Detected test suites (label + argv + routing scope/cwd), frozen at generation time. */
const SUITES = [
${suiteLines}
];

${generatedHelpersSource()}${generatedRoutingSource()}/**
 * Register the \`test\` tool on the host extension API.
 *
 * @param pi - ExtensionAPI of the host process.
 */
export default function testToolExtension(pi) {
  pi.registerTool({
    name: "test",
    label: "Run tests",
    description:
      "Run the project's test suites sequentially and report pass/fail with a " +
      "labeled output tail. The optional scope/run filters are iteration only — " +
      "a filtered run never satisfies the done criteria. Errors when any suite fails.",
    parameters: {
      type: "object",
      properties: {
        scope: {
          type: "array",
          items: { type: "string" },
          description:
            "Repo-relative path filter: routed per suite by language and " +
            "deepest-ancestor cwd; suites with no routed paths are skipped.",
        },
        run: {
          type: "string",
          description: "Test-name regex for go test suites, passed as -run <regex>.",
        },
      },
      additionalProperties: false,
    },
    async execute(toolCallId, params, signal, onUpdate, ctx) {
      const scope = params && Array.isArray(params.scope) ? params.scope : undefined;
      const run = params && typeof params.run === "string" && params.run ? params.run : undefined;
      // Structured params only (T7): a malformed scope entry rejects the whole
      // call before anything runs — no free-form argv smuggling.
      if (scope) {
        for (const entry of scope) {
          if (!validScopeEntry(entry)) {
            return {
              content: [{
                type: "text",
                text:
                  "invalid scope entry: " + JSON.stringify(entry) +
                  " — scope entries must be repo-relative paths matching " +
                  "[a-zA-Z0-9._/-], with no leading '-' and no '..'. Nothing was run.",
              }],
              isError: true,
            };
          }
        }
      }
      const filtered = Boolean((scope && scope.length > 0) || run);
      const payload = await readUnitPayload();
      // Default scope for a no-args run: the unit payload's owned test files.
      const paths =
        scope && scope.length > 0
          ? scope
          : payload && payload.unit && Array.isArray(payload.unit.testFiles)
            ? payload.unit.testFiles
            : [];
      const runs = routeSuites(SUITES, paths.map((p) => ({ path: p })));
      // Per-suite cwd: payload repoRoot joined with the suite cwd, falling
      // back to the tool-context cwd when no payload is present.
      const { join } = await import("node:path");
      const repoRoot = (payload && payload.repoRoot) || ctx.cwd;
      const timeout = suiteTimeoutMs();
      const sections = [];
      const failures = [];
      let ran = 0;
      for (const item of runs) {
        const suite = item.suite;
        if (item.skipped) {
          sections.push(
            "## " + suite.label + "\\nsuite '" + suite.label +
              "' skipped (no routed paths)" +
              (filtered ? " — filtered iteration run, not verification" : ""),
          );
          continue;
        }
        const argv = withRun(item.argv, run);
        ran++;
        let result;
        try {
          result = await pi.exec(argv[0], argv.slice(1), {
            cwd: join(repoRoot, suite.cwd || "."),
            timeout,
          });
        } catch (err) {
          failures.push(suite.label);
          sections.push(
            "## " + suite.label + "\\nspawn failed: " + String((err && err.message) || err),
          );
          continue;
        }
        const ok = result.code === 0 && !result.killed;
        if (!ok) failures.push(suite.label);
        const out =
          tail([result.stdout, result.stderr].filter(Boolean).join("\\n")) || "(no output)";
        sections.push(
          "## " + suite.label +
            "\\nexit " + result.code +
            (result.killed ? " (killed)" : "") +
            "\\n" + out,
        );
      }
      const summary =
        failures.length === 0
          ? "all " + ran + " suite(s) passed"
          : failures.length + "/" + ran + " suite(s) failed: " + failures.join("; ");
      // Every filtered result carries the header first: n = suites run,
      // m = total suites known at generation time.
      const header = filtered
        ? "filtered run — " + ran + "/" + SUITES.length +
          " suites — does not satisfy the done criteria"
        : "";
      const text = (header ? header + "\\n" : "") + summary + "\\n\\n" + sections.join("\\n\\n");
      return failures.length === 0
        ? { content: [{ type: "text", text: text }] }
        : { content: [{ type: "text", text: text }], isError: true };
    },
  });
}
`;
}
